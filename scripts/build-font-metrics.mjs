#!/usr/bin/env node
// Builds src/core/svg-render/font-metrics.ts (advance widths) from two TrueType files.
// DEV-TIME ONLY: tests and `npm run check` never run this and never read a font file.
//
//   node scripts/build-font-metrics.mjs <regular.ttf> <bold.ttf>
//
// Use Liberation Sans Regular/Bold (SIL OFL) or Windows' own arial.ttf / arialbd.ttf. Reads
// head.unitsPerEm, hhea.numberOfHMetrics, hmtx and the cmap (format 4); no dependencies, no
// network. Same fonts in, same bytes out (sorted by code point, LF line ends).
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'core',
  'svg-render',
  'font-metrics.ts',
);

// Coverage (SPEC-svg-render.md "Text measurement"); code points the font lacks are skipped.
const RANGES = [
  [0x20, 0x7e],
  [0xa0, 0xff],
  [0x391, 0x3c9],
  [0x2013, 0x2014],
  [0x2018, 0x2019],
  [0x201c, 0x201d],
  [0x2020, 0x2022],
  [0x2026, 0x2026],
  [0x2190, 0x2195],
  [0x2212, 0x2212],
];

function readFont(file) {
  const buf = readFileSync(file);
  const u16 = (o) => buf.readUInt16BE(o);
  const tables = {};
  for (let i = 0, n = u16(4); i < n; i++) {
    const rec = 12 + i * 16;
    tables[buf.toString('latin1', rec, rec + 4)] = buf.readUInt32BE(rec + 8);
  }
  for (const t of ['head', 'hhea', 'hmtx', 'cmap']) {
    if (tables[t] === undefined) throw new Error(`${file}: no ${t} table`);
  }
  const unitsPerEm = u16(tables.head + 18);
  const hMetrics = u16(tables.hhea + 34);

  // cmap: the format 4 subtable (prefer Windows Unicode BMP).
  const cmap = tables.cmap;
  let sub = -1;
  for (let i = 0, n = u16(cmap + 2); i < n; i++) {
    const rec = cmap + 4 + i * 8;
    const offset = cmap + buf.readUInt32BE(rec + 4);
    if (u16(offset) !== 4) continue;
    if (sub < 0 || (u16(rec) === 3 && u16(rec + 2) === 1)) sub = offset;
  }
  if (sub < 0) throw new Error(`${file}: no cmap format 4 subtable`);
  const segs = u16(sub + 6) / 2;
  const endCodes = sub + 14;
  const startCodes = endCodes + segs * 2 + 2;
  const deltas = startCodes + segs * 2;
  const rangeOffsets = deltas + segs * 2;

  const glyphOf = (cp) => {
    for (let s = 0; s < segs; s++) {
      if (cp > u16(endCodes + s * 2)) continue;
      if (cp < u16(startCodes + s * 2)) return 0;
      const delta = u16(deltas + s * 2);
      const ro = u16(rangeOffsets + s * 2);
      if (ro === 0) return (cp + delta) & 0xffff;
      const gid = u16(rangeOffsets + s * 2 + ro + (cp - u16(startCodes + s * 2)) * 2);
      return gid === 0 ? 0 : (gid + delta) & 0xffff;
    }
    return 0;
  };

  const advances = new Map();
  for (const [from, to] of RANGES) {
    for (let cp = from; cp <= to; cp++) {
      const gid = glyphOf(cp);
      if (gid === 0) continue;
      const adv = u16(tables.hmtx + Math.min(gid, hMetrics - 1) * 4);
      advances.set(cp, Math.round((adv * 1000) / unitsPerEm));
    }
  }
  return { advances, sha: createHash('sha256').update(buf).digest('hex'), name: basename(file) };
}

function table(name, advances) {
  const rows = [...advances].sort((a, b) => a[0] - b[0]).map(([cp, w]) => `  ${cp}: ${w},`);
  return [`export const ${name}: Readonly<Record<number, number>> = {`, ...rows, '};'];
}

const [regularFile, boldFile] = process.argv.slice(2);
if (!regularFile || !boldFile) {
  console.error('usage: node scripts/build-font-metrics.mjs <regular.ttf> <bold.ttf>');
  process.exit(2);
}
const regular = readFont(regularFile);
const bold = readFont(boldFile);
const lines = [
  '// GENERATED by scripts/build-font-metrics.mjs. Do not edit; regenerate from the fonts.',
  `// Regular: ${regular.name}  SHA-256 ${regular.sha}`,
  `// Bold:    ${bold.name}  SHA-256 ${bold.sha}`,
  '// Advance widths in 1/1000 em, keyed by code point, sorted. See SPEC-svg-render.md.',
  '',
  'export const UNITS_PER_EM = 1000;',
  '',
  ...table('ADVANCE_REGULAR', regular.advances),
  '',
  ...table('ADVANCE_BOLD', bold.advances),
  '',
];
writeFileSync(OUT, lines.join('\n'));
console.log(`wrote ${OUT} (${regular.advances.size} regular, ${bold.advances.size} bold glyphs)`);
