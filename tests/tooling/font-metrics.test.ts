import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import {
  ADVANCE_BOLD,
  ADVANCE_REGULAR,
  UNITS_PER_EM,
} from '../../src/core/svg-render/font-metrics';

// Coverage of SPEC-svg-render.md "Text measurement". U+03A2 is unassigned in Unicode.
const RANGES: readonly (readonly [number, number])[] = [
  [0x20, 0x7e],
  [0xa0, 0xff],
  [0x391, 0x3c9],
  [0x2013, 0x2014],
  [0x2018, 0x2019],
  [0x201c, 0x201d],
  [0x2020, 0x2022],
  [0x2026, 0x2026],
  [0x2190, 0x2195],
  [0x2212, 0x2212],
];
const UNASSIGNED = new Set([0x3a2]);

const EXPECTED_COUNT = RANGES.reduce((n, [from, to]) => n + (to - from + 1), 0) - UNASSIGNED.size;

const cp = (ch: string) => ch.codePointAt(0)!;

describe('font metrics table', () => {
  it('uses 1000 units per em', () => {
    expect(UNITS_PER_EM).toBe(1000);
  });

  it.each([
    ['W', 944],
    ['i', 222],
    ['0', 556],
    ['m', 833],
    ['−', 584],
    [' ', 278],
  ])('regular %s is %d', (ch, width) => {
    expect(ADVANCE_REGULAR[cp(ch)]).toBe(width);
  });

  it('bold W is 944, bold i is 278', () => {
    expect(ADVANCE_BOLD[cp('W')]).toBe(944);
    expect(ADVANCE_BOLD[cp('i')]).toBe(278);
  });

  it.each([
    ['regular', ADVANCE_REGULAR],
    ['bold', ADVANCE_BOLD],
  ] as const)('%s covers every range', (_name, table) => {
    for (const [from, to] of RANGES) {
      for (let c = from; c <= to; c++) {
        if (UNASSIGNED.has(c)) continue;
        expect(table[c], `U+${c.toString(16).toUpperCase()}`).toBeDefined();
      }
    }
  });

  it.each([
    ['regular', ADVANCE_REGULAR],
    ['bold', ADVANCE_BOLD],
  ] as const)('%s has integer widths and nothing outside the ranges', (_name, table) => {
    for (const [key, width] of Object.entries(table)) {
      const c = Number(key);
      expect(Number.isInteger(width) && width > 0 && width < 2000, `U+${key} = ${width}`).toBe(
        true,
      );
      expect(RANGES.some(([from, to]) => c >= from && c <= to)).toBe(true);
    }
  });

  it('is sorted by code point in the committed source, with LF line ends and a header', () => {
    const source = readFileSync('src/core/svg-render/font-metrics.ts', 'utf8');
    expect(source).not.toContain('\r');
    expect(source.startsWith('// GENERATED by scripts/build-font-metrics.mjs')).toBe(true);
    expect(source).toMatch(/Regular: \S+\.ttf {2}SHA-256 [0-9a-f]{64}/);
    expect(source).toMatch(/Bold: {4}\S+\.ttf {2}SHA-256 [0-9a-f]{64}/);
    for (const name of ['ADVANCE_REGULAR', 'ADVANCE_BOLD']) {
      const body = source.split(`export const ${name}`)[1]!.split('};')[0]!;
      const keys = [...body.matchAll(/^ {2}(\d+): \d+,$/gm)].map((m) => Number(m[1]));
      expect(keys).toHaveLength(EXPECTED_COUNT);
      expect(keys).toEqual([...keys].sort((a, b) => a - b));
      expect(new Set(keys).size).toBe(keys.length);
    }
  });

  it('keeps regular and bold in step on digits (Arial: all 556)', () => {
    for (let c = cp('0'); c <= cp('9'); c++) {
      expect(ADVANCE_REGULAR[c]).toBe(556);
      expect(ADVANCE_BOLD[c]).toBe(556);
    }
  });
});
